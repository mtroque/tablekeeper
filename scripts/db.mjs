// `pnpm db:start | db:reset | db:types`. Start and reset act on the one local Supabase shared by
// every worktree, so they only run from the main checkout (AGENTS.md → Parallel sessions).
import { execFileSync, spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { loadEnvFile, ROOT } from './lib/local-env.mjs';
import { inWorktree } from './lib/worktree.mjs';

const command = process.argv[2];
const TYPES_FILE = join(ROOT, 'apps/api/src/db/database.types.ts');

function run(args) {
  const result = spawnSync('supabase', args, { cwd: ROOT, stdio: 'inherit', env: process.env });
  process.exit(result.status ?? 1);
}

if ((command === 'start' || command === 'reset') && inWorktree()) {
  console.error(
    `pnpm db:${command} only runs from the main checkout; worktrees share its database.`,
  );
  process.exit(1);
}

switch (command) {
  case 'start':
    // Supabase reads the Google OAuth client from these (supabase/config.toml).
    loadEnvFile();
    process.env.SUPABASE_AUTH_EXTERNAL_GOOGLE_CLIENT_ID ??= '';
    process.env.SUPABASE_AUTH_EXTERNAL_GOOGLE_SECRET ??= '';
    run(['start']);
    break;
  case 'reset':
    run(['db', 'reset']);
    break;
  case 'types': {
    const types = execFileSync('supabase', ['gen', 'types', 'typescript', '--local'], {
      cwd: ROOT,
      encoding: 'utf8',
    });
    writeFileSync(TYPES_FILE, `// Generated by \`pnpm db:types\`. Do not edit.\n${types}`);
    console.log(`Wrote ${TYPES_FILE}`);
    break;
  }
  default:
    console.error('Usage: node scripts/db.mjs start|reset|types');
    process.exit(1);
}
